// Package deployment reads bounded host publication evidence without Docker access.
package deployment

import (
	"encoding/json"
	"errors"
	"io"
	"net"
	"os"
	"path/filepath"
	"strings"
	"time"
	"weroxy/server/internal/ports"
)

// FilterDataPool is opt-in for Docker bridge deployments. Unknown or stale
// publication cannot be treated as an unrestricted pool in this mode.
func FilterDataPool(dataDir string, pool ports.Pool) (ports.Pool, error) {
	plan, err := HostPortPlan(dataDir)
	if err != nil {
		return pool, err
	}
	if plan != nil {
		if plan.DataFirst != pool.First || plan.DataLast != pool.Last {
			return pool, errors.New("host_port_plan_mismatch")
		}
		pool.Unavailable = map[int]bool{}
		for _, port := range plan.UnavailableData {
			pool.Unavailable[port] = true
		}
	}
	if os.Getenv("WEROXY_REQUIRE_PUBLICATION") != "1" {
		return pool, nil
	}
	var snapshot struct {
		ContainerID string `json:"container_id"`
		CheckedAt   string `json:"checked_at"`
		Ports       []struct {
			ContainerPort int    `json:"container_port"`
			HostIP        string `json:"host_ip"`
			HostPort      int    `json:"host_port"`
		} `json:"ports"`
	}
	path := filepath.Join(dataDir, "deployment-publication.json")
	info, err := os.Lstat(path)
	if err != nil || !info.Mode().IsRegular() || info.Size() < 1 || info.Size() > 64<<10 {
		return pool, errors.New("publication_unverified")
	}
	file, err := os.Open(path)
	if err != nil {
		return pool, errors.New("publication_unverified")
	}
	defer file.Close()
	opened, err := file.Stat()
	if err != nil || !os.SameFile(info, opened) {
		return pool, errors.New("publication_unverified")
	}
	decoder := json.NewDecoder(io.LimitReader(file, (64<<10)+1))
	decoder.DisallowUnknownFields()
	var extra any
	if decoder.Decode(&snapshot) != nil || !errors.Is(decoder.Decode(&extra), io.EOF) || len(snapshot.Ports) > 1024 {
		return pool, errors.New("publication_unverified")
	}
	hostname, err := os.Hostname()
	checked, timeErr := time.Parse(time.RFC3339Nano, snapshot.CheckedAt)
	if err != nil || len(hostname) < 12 || !strings.HasPrefix(snapshot.ContainerID, hostname) || timeErr != nil || checked.After(time.Now().Add(time.Minute)) || time.Since(checked) > 2*time.Minute {
		return pool, errors.New("publication_unverified")
	}
	published := map[int]bool{}
	for _, binding := range snapshot.Ports {
		ip := net.ParseIP(binding.HostIP)
		if ip == nil || binding.ContainerPort < 1 || binding.ContainerPort > 65535 || binding.HostPort < 1 || binding.HostPort > 65535 {
			return pool, errors.New("publication_unverified")
		}
		// OPEN currently advertises the data listener's port. Remapped or loopback
		// host bindings cannot serve that address to remote clients.
		if !ip.IsLoopback() && binding.HostPort == binding.ContainerPort {
			published[binding.ContainerPort] = true
		}
	}
	unavailable := map[int]bool{}
	for port, value := range pool.Unavailable {
		unavailable[port] = value
	}
	for port := pool.First; port <= pool.Last; port++ {
		if !published[port] {
			unavailable[port] = true
		}
	}
	pool.Unavailable = unavailable
	return pool, nil
}

// HostPlan is generated by the host deployment manager before Docker startup.
type HostPlan struct {
	CheckedAt          string `json:"checked_at"`
	ForwardFirst       int    `json:"forward_first"`
	ForwardLast        int    `json:"forward_last"`
	DataFirst          int    `json:"data_first"`
	DataLast           int    `json:"data_last"`
	UnavailableForward []int  `json:"unavailable_forward"`
	UnavailableData    []int  `json:"unavailable_data"`
}

func HostPortPlan(dataDir string) (*HostPlan, error) {
	path := filepath.Join(dataDir, "host-port-plan.json")
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil || !info.Mode().IsRegular() || info.Size() < 1 || info.Size() > 64<<10 {
		return nil, errors.New("host_port_plan_invalid")
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var plan HostPlan
	if json.Unmarshal(raw, &plan) != nil {
		return nil, errors.New("host_port_plan_invalid")
	}
	checked, err := time.Parse(time.RFC3339Nano, plan.CheckedAt)
	if err != nil || checked.After(time.Now().Add(time.Minute)) {
		return nil, errors.New("host_port_plan_stale")
	}
	if plan.ForwardFirst < 1 || plan.ForwardLast > 65535 || plan.DataFirst < 1 || plan.DataLast > 65535 || plan.ForwardLast < plan.ForwardFirst || plan.DataLast < plan.DataFirst {
		return nil, errors.New("host_port_plan_invalid")
	}
	for _, port := range plan.UnavailableForward {
		if port < plan.ForwardFirst || port > plan.ForwardLast {
			return nil, errors.New("host_port_plan_invalid")
		}
	}
	for _, port := range plan.UnavailableData {
		if port < plan.DataFirst || port > plan.DataLast {
			return nil, errors.New("host_port_plan_invalid")
		}
	}
	return &plan, nil
}
